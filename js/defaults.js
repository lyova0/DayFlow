// Начальное расписание. Создаётся один раз при первом запуске,
// потом его можно свободно редактировать в разделе «Расписание».
// Длительность событий не задаётся — её никто не называл.
// time: '' означает «время пока неизвестно».

export function buildDefaults(newId) {
  const schedule = {};
  const add = (day, time, title, kind) => {
    schedule[newId()] = { title, kind, day, time, repeat: 'weekly' };
  };

  // 1 = понедельник ... 6 = суббота, 0 = воскресенье
  [1, 2, 3, 4, 5].forEach((day) => add(day, '08:00', 'Школа', 'school'));

  [1, 3, 5].forEach((day) => {
    add(day, '15:00', 'Математика', 'math');
    add(day, '18:00', 'Английский', 'english');
  });

  [2, 4].forEach((day) => add(day, '20:00', 'Тренажёрный зал', 'gym'));

  add(6, '16:30', 'Английский', 'english');
  add(6, '', 'Плавание', 'swim'); // время уточнить позже

  // Воскресенье — свободный день, событий нет.
  return schedule;
}
